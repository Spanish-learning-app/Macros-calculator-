import { open, shot, fullshot, txt } from './lib.mjs';
const { browser, page } = await open();
const t0 = Date.now();
await page.getByRole('button',{name:'Start'}).click();
await page.locator('input[value=female]').click();
await page.locator('input[type=text]').nth(0).fill('42');
await page.locator('input[type=radio]').nth(3).click();
const ins = page.locator('input[inputmode=decimal]');
await ins.nth(1).fill('5');
await ins.nth(2).fill('3');
await ins.nth(3).fill('70');
await page.locator('input[value=lose]').click().catch(async()=>{ await page.getByText('Lose weight').click(); });
await shot(page, '04-onboarding-filled');
await page.getByRole('button',{name:'See my targets'}).click();
await page.waitForTimeout(600);
await shot(page, '05-after-onboarding');
await fullshot(page, '05-after-onboarding-full');
console.log(await txt(page));
console.log('ms', Date.now()-t0);
await browser.close();
