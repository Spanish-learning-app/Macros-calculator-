import * as L from './lib.mjs';
const run = await L.launch(); const p = run.page;
await L.onboardP1(run);
console.log('onboarding actions', run.actions);
await L.shot(run,'d0-00-empty-day');
L.start(run);
const sh = L.sheet(run);
const pick = async (q, re, how) => {
  await L.search(run, q);
  const row = L.rows(run).filter({hasText:re}).first();
  console.log(`  [${q}] top rows:`, (await L.rowTexts(run,3)).map(s=>s.split(' | ').filter(x=>!/^[؀-ۿ ]+$/.test(x)).join(' / ')).join(' || '));
  if (how === 'plus') await L.tap(run,row.locator('.btn-plus'));
  return row;
};
const setMeal = async (label) => { await L.tap(run, sh.locator('select')); await sh.locator('select').selectOption({label}); run.actions += 0; };
await L.openSlot(run,'Nashta');
await pick('anda paratha',/paratha/i,'plus');
await pick('chai',/1 tsp sugar/,'plus');
await L.shot(run,'d0-01-nashta-added');
await sh.locator('select').selectOption({label:'Lunch'}); run.actions++;
await pick('daal chawal',/Daal chawal/,'plus');
await sh.locator('select').selectOption({label:'Shaam ki chai'}); run.actions++;
await pick('chai',/1 tsp sugar/,'plus');
const bis = await pick('biscuit',/Marie/i,null);
const qty = async (row, label) => {
  await L.tap(run, row.locator('.food-main'));
  await p.waitForSelector('[data-testid=portion-picker]');
  await L.tap(run, p.locator('[data-testid=portion-picker]').getByRole('button',{name:label,exact:true}));
  console.log('  picker preview:', (await p.locator('[data-testid=portion-preview]').innerText()).replace(/\n+/g,' | '));
  await L.tap(run, p.locator('[data-testid=portion-picker]').getByRole('button',{name:/^Add to/}));
  await p.waitForTimeout(300);
};
await qty(bis,'2');
await L.shot(run,'d0-03-after-biscuit');
await sh.locator('select').selectOption({label:'Dinner'}); run.actions++;
await pick('karahi',/Chicken karahi \(home/,'plus');
const roti = await pick('roti',/Roti \/ chapati/,null);
await qty(roti,'2');
await L.tap(run, sh.getByRole('button',{name:'Done'}));
await p.waitForTimeout(300);
const secs = L.elapsed(run);
console.log('D0 ACTIONS', run.actions, 'paced seconds', secs);
await L.shot(run,'d0-04-day-final');
console.log('ENTRIES'); for (const e of await L.entries(run)) console.log('  ',e);
console.log(await L.totals(run));
await p.evaluate(()=>window.scrollTo(0,0));
const full = await p.innerText('body'); console.log(full.replace(/\n+/g,' | '));
console.log('errors',run.errors,'foreign',run.foreign);
await run.browser.close();
