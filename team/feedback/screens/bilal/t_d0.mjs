await pick('daal chawal',/Daal chawal/,'plus');
await sh.locator('select').selectOption({label:'Shaam ki chai'}); run.actions++;
await pick('chai',/1 tsp sugar/,'plus');
const bis = await pick('biscuit',/Marie|biscuit/i,null);
await L.tap(run, bis.locator('.food-main'));
await p.waitForSelector('[data-testid=portion-picker]');
await L.shot(run,'d0-02-biscuit-picker');
console.log('picker text:', (await p.innerText('[data-testid=portion-picker]')).replace(/\n+/g,' | '));
await p.screenshot({path:L.OUT+'d0-02b.png'});
