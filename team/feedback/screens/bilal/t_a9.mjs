import * as L from './lib.mjs';
const run = await L.launch({time:'2026-10-14T21:00:00+02:00'}); const p = run.page;
await L.onboardP1(run);
await L.openSlot(run,'Dinner');
const pk = p.locator('[data-testid=portion-picker]');
const prev = async()=> (await p.locator('[data-testid=portion-preview]').innerText()).replace(/\n+/g,' | ');
L.start(run);
await L.search(run,'karahi');
await L.tap(run, L.rows(run).filter({hasText:/Chicken karahi \(home/}).first().locator('.food-main'));
await pk.waitFor(); await p.waitForTimeout(350);
await L.shot(run,'a9-01-karahi-home');
console.log('home picker:', (await pk.innerText()).replace(/\n+/g,' | '));
const sw = pk.locator('[data-testid=variant-switch]');
console.log('variant switch present', await sw.count(), (await sw.innerText().catch(()=>'')).replace(/\n+/g,' | '));
const home = await prev();
const s0=run.actions;
await L.tap(run, sw.locator('label,button').filter({hasText:/Restaurant/}).first());
await p.waitForTimeout(300);
console.log('switch actions', run.actions-s0);
console.log('restaurant picker:', (await pk.innerText()).replace(/\n+/g,' | ').slice(0,500));
await L.shot(run,'a9-02-karahi-restaurant');
console.log('home preview', home, '\nrest preview', await prev());
console.log('serving selected after switch:', await pk.locator('input[type=radio]:checked').evaluateAll(els=>els.map(e=>e.value)));
console.log('options in switch:', await sw.locator('label,button').allInnerTexts());
// source
const s1=run.actions;
await L.tap(run, pk.getByRole('button',{name:/Source and details/}));
await p.waitForTimeout(400);
await L.shot(run,'a9-03-source');
console.log('source actions', run.actions-s1);
const fd = p.locator('[data-testid=food-details]');
console.log('SOURCE TEXT:', (await fd.innerText()).replace(/\n+/g,' | '));
// close the source
await L.tap(run, fd.getByRole('button',{name:/Close|Back|Done/}).first());
await p.waitForTimeout(300);
console.log('after closing source, picker visible', await pk.isVisible(), 'preview', await prev());
await L.shot(run,'a9-04-after-close-source');
await L.tap(run, pk.getByRole('button',{name:/^Add to/}));
await p.waitForTimeout(300);
await L.done(run);
const ent = p.locator('[data-testid=entry]').first();
console.log('entry:', (await ent.innerText()).replace(/\n+/g,' | '));
await L.shot(run,'a9-05-day-entry');
// source from entry: via entry -> picker -> Source
await L.tap(run, ent.locator('.entry-main'));
await pk.waitFor(); await p.waitForTimeout(300);
await L.tap(run, pk.getByRole('button',{name:/Source and details/}));
await p.waitForTimeout(300);
console.log('source from entry opened', await fd.isVisible(), 'actions total', run.actions);
await L.shot(run,'a9-06-source-from-entry');
console.log('errors', run.errors, run.dialogs);
await run.browser.close();
